import {
  파이썬_반올림, 회색조로, 배경이_밝으면_반전, 글씨영역_자르기,
  무게중심_이동, 그림만들기,
} from "../preprocess.js";
import { 검사, 같아야, 배열이_가까워야 } from "../test_runner.js";

export function preprocess_테스트_등록() {
  검사("파이썬_반올림: .5 는 짝수 쪽으로 간다", () => {
    // 파이썬 round() 는 은행가 반올림이고 JS Math.round() 는 항상 올림이다.
    // 긴 변 20px 축소에서 1픽셀이 어긋나면 이후 전부 틀어진다.
    같아야(파이썬_반올림(0.5), 0, "round(0.5)");
    같아야(파이썬_반올림(1.5), 2, "round(1.5)");
    같아야(파이썬_반올림(2.5), 2, "round(2.5)");
    같아야(파이썬_반올림(3.5), 4, "round(3.5)");
    같아야(파이썬_반올림(-0.5), 0, "round(-0.5)");
    같아야(파이썬_반올림(-1.5), -2, "round(-1.5)");
    같아야(파이썬_반올림(-2.5), -2, "round(-2.5)");
    같아야(파이썬_반올림(2.4), 2, "round(2.4)");
    같아야(파이썬_반올림(2.6), 3, "round(2.6)");
  });

  검사("회색조로: R=G=B 면 그 값이 그대로 나온다", () => {
    const RGBA = new Uint8ClampedArray([
      10, 10, 10, 255, 200, 200, 200, 255,
      0, 0, 0, 255, 255, 255, 255, 255,
    ]);
    const 그림 = 회색조로(2, 2, RGBA);
    같아야(그림.너비, 2, "너비");
    같아야(그림.높이, 2, "높이");
    배열이_가까워야(그림.화소, [10, 200, 0, 255], 0, "회색조 값");
  });

  검사("배경이_밝으면_반전: 흰 배경이면 뒤집는다", () => {
    // 4x4 전부 255 -> 가장자리 평균 255 > 127 -> 반전 -> 전부 0
    const 그림 = 그림만들기(4, 4, new Uint8ClampedArray(16).fill(255));
    const 결과 = 배경이_밝으면_반전(그림);
    배열이_가까워야(결과.화소, new Array(16).fill(0), 0, "반전 결과");
  });

  검사("배경이_밝으면_반전: 검은 배경이면 그대로 둔다", () => {
    const 화소 = new Uint8ClampedArray(16).fill(0);
    화소[5] = 255;                       // 가운데 한 점만 밝게
    const 결과 = 배경이_밝으면_반전(그림만들기(4, 4, 화소));
    배열이_가까워야(결과.화소, 화소, 0, "그대로 유지");
  });

  검사("배경이_밝으면_반전: 모서리를 두 번 세는 파이썬 동작을 따른다", () => {
    // preprocess.py 는 np.concatenate([첫행, 끝행, 첫열, 끝열]) 로 가장자리를
    // 모으는데, 네 모서리가 두 번씩 들어간다. 이 중복을 그대로 재현해야
    // 반전 판단이 파이썬과 같아진다.
    //
    // 3x3 에서 모서리 4개만 255, 나머지 0 인 경우:
    //   중복 세는 방식: 표본 12개 중 모서리가 8번 -> 평균 8*255/12 = 170 > 127 (반전)
    //   중복 없는 방식: 표본 8개 중 모서리가 4번 -> 평균 4*255/8 = 127.5 > 127 (반전)
    // 둘 다 반전이라 구분이 안 되므로, 모서리를 3개만 켜서 갈리게 한다:
    //   중복 세는 방식: 6*255/12 = 127.5 > 127 -> 반전
    //   중복 없는 방식: 3*255/8  = 95.6 <= 127 -> 유지
    const 화소 = new Uint8ClampedArray(9).fill(0);
    화소[0] = 255;   // (0,0)
    화소[2] = 255;   // (2,0)
    화소[6] = 255;   // (0,2)
    const 결과 = 배경이_밝으면_반전(그림만들기(3, 3, 화소));
    같아야(결과.화소[4], 255, "가운데가 반전되어 255 가 된다");
  });

  검사("글씨영역_자르기: 밝기 30 초과인 최소 사각형을 낸다", () => {
    // 5x5 에서 (1,1)~(2,3) 만 밝게
    const 화소 = new Uint8ClampedArray(25).fill(0);
    for (const [x, y] of [[1, 1], [2, 1], [1, 3], [2, 3]]) 화소[y * 5 + x] = 200;
    const 결과 = 글씨영역_자르기(그림만들기(5, 5, 화소));
    같아야(결과.너비, 2, "잘린 너비");
    같아야(결과.높이, 3, "잘린 높이");
    배열이_가까워야(결과.화소, [200, 200, 0, 0, 200, 200], 0, "잘린 내용");
  });

  검사("글씨영역_자르기: 임계값 30 이하는 배경으로 본다", () => {
    const 화소 = new Uint8ClampedArray(9).fill(30);   // 30 은 '초과' 가 아니다
    같아야(글씨영역_자르기(그림만들기(3, 3, 화소)), null, "글씨 없음");
  });

  검사("글씨영역_자르기: 빈 그림이면 null (Review Focus 1)", () => {
    const 그림 = 그림만들기(8, 8, new Uint8ClampedArray(64).fill(0));
    같아야(글씨영역_자르기(그림), null, "빈 그림은 null");
  });

  검사("무게중심_이동: 밝은 점을 중앙으로 옮긴다", () => {
    // (4,4) 에 한 점. 중심 = (4,4). 이동량 = round(13.5-4) = round(9.5) = 10 (짝수)
    // 따라서 (14,14) 로 간다.
    const 화소 = new Uint8ClampedArray(784).fill(0);
    화소[4 * 28 + 4] = 255;
    const 결과 = 무게중심_이동(그림만들기(28, 28, 화소));
    같아야(결과.화소[14 * 28 + 14], 255, "(14,14) 로 이동");
    같아야(결과.화소[4 * 28 + 4], 0, "원래 자리는 비었다");
  });

  검사("무게중심_이동: 이미 중앙이면 그대로 둔다", () => {
    // (13,13),(14,13),(13,14),(14,14) 네 점의 중심은 정확히 (13.5, 13.5)
    const 화소 = new Uint8ClampedArray(784).fill(0);
    for (const [x, y] of [[13, 13], [14, 13], [13, 14], [14, 14]]) {
      화소[y * 28 + x] = 255;
    }
    const 결과 = 무게중심_이동(그림만들기(28, 28, 화소));
    배열이_가까워야(결과.화소, 화소, 0, "변화 없음");
  });

  검사("무게중심_이동: 전부 0 이면 그대로 둔다 (Review Focus 1)", () => {
    const 화소 = new Uint8ClampedArray(784).fill(0);
    const 결과 = 무게중심_이동(그림만들기(28, 28, 화소));
    배열이_가까워야(결과.화소, 화소, 0, "0 으로 나누지 않는다");
  });

  검사("무게중심_이동: 캔버스 구석에 그려도 중앙으로 온다", () => {
    // (27,27) 한 점. 이동량 = round(13.5-27) = round(-13.5) = -14 (짝수)
    // 27 + (-14) = 13 이므로 (13,13) 으로 간다.
    const 화소 = new Uint8ClampedArray(784).fill(0);
    화소[27 * 28 + 27] = 255;
    const 결과 = 무게중심_이동(그림만들기(28, 28, 화소));
    같아야(결과.화소[13 * 28 + 13], 255, "(13,13) 로 이동");
    let 합 = 0;
    for (const 값 of 결과.화소) 합 += 값;
    같아야(합, 255, "점이 하나만 남는다");
  });
}
