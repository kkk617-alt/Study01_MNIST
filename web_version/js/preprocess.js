// 손으로 그린 그림을 MNIST 형식(28x28)으로 바꾸는 전처리.
//
// desktop_version/preprocess.py 를 그대로 옮긴 것이다. 단계 순서와 수치가
// 파이썬과 같아야 두 버전의 인식 결과가 일치한다. "더 올바른" 구현으로
// 고치고 싶어지는 자리가 몇 군데 있는데, 고치면 결과가 갈린다.
//
// 그림 객체 형태: { 너비, 높이, 화소 } — 화소는 Uint8ClampedArray, 행 우선.
// 이 파일은 DOM 을 참조하지 않는다.

/** 그림 객체를 만든다. 화소를 주지 않으면 0 으로 채운다. */
export function 그림만들기(너비, 높이, 화소 = null) {
  return {
    너비,
    높이,
    화소: 화소 ?? new Uint8ClampedArray(너비 * 높이),
  };
}

/**
 * 파이썬 round() 와 같은 짝수 반올림.
 *
 * JS 의 Math.round() 는 .5 에서 항상 큰 쪽으로 붙지만 파이썬은 짝수 쪽으로
 * 붙는다. 긴 변 20px 축소에서 1픽셀이 어긋나면 이후 모든 픽셀이 밀린다.
 */
export function 파이썬_반올림(값) {
  const 내림 = Math.floor(값);
  const 나머지 = 값 - 내림;
  if (나머지 > 0.5) return 내림 + 1;
  if (나머지 < 0.5) return 내림;
  return 내림 % 2 === 0 ? 내림 : 내림 + 1;
}

/**
 * RGBA 바이트 배열을 회색조 그림으로 바꾼다.
 *
 * PIL 의 convert("L") 과 같은 고정소수점 식을 쓴다.
 * 19595 + 38470 + 7471 = 65536 이므로 R=G=B 인 입력은 그 값이 그대로 나온다.
 * 캔버스는 흰 선만 그리므로 실제로는 항상 그 경우다.
 */
export function 회색조로(너비, 높이, RGBA바이트) {
  const 화소 = new Uint8ClampedArray(너비 * 높이);
  for (let i = 0; i < 화소.length; i += 1) {
    const 기준 = i * 4;
    화소[i] = (RGBA바이트[기준] * 19595 +
               RGBA바이트[기준 + 1] * 38470 +
               RGBA바이트[기준 + 2] * 7471 + 0x8000) >> 16;
  }
  return 그림만들기(너비, 높이, 화소);
}

/**
 * MNIST 는 검은 배경에 흰 글씨다. 배경이 밝으면 뒤집는다.
 *
 * 가장자리 표본을 모으는 방식이 preprocess.py 와 같아야 한다. 파이썬은
 * np.concatenate([첫행, 끝행, 첫열, 끝열]) 로 모으는데 네 모서리가 두 번씩
 * 들어간다. 이 중복을 일부러 그대로 재현한다 — 고치면 경계 사례에서 반전
 * 판단이 갈려 결과 전체가 뒤집힌다.
 */
export function 배경이_밝으면_반전(그림) {
  const { 너비, 높이, 화소 } = 그림;
  let 합 = 0;
  let 개수 = 0;

  for (let x = 0; x < 너비; x += 1) {           // 첫 행
    합 += 화소[x]; 개수 += 1;
  }
  for (let x = 0; x < 너비; x += 1) {           // 끝 행
    합 += 화소[(높이 - 1) * 너비 + x]; 개수 += 1;
  }
  for (let y = 0; y < 높이; y += 1) {           // 첫 열
    합 += 화소[y * 너비]; 개수 += 1;
  }
  for (let y = 0; y < 높이; y += 1) {           // 끝 열
    합 += 화소[y * 너비 + (너비 - 1)]; 개수 += 1;
  }

  if (합 / 개수 <= 127) return 그림;

  const 반전된 = new Uint8ClampedArray(화소.length);
  for (let i = 0; i < 화소.length; i += 1) 반전된[i] = 255 - 화소[i];
  return 그림만들기(너비, 높이, 반전된);
}

/**
 * 밝기 30 초과인 화소의 최소 사각형만 남긴다.
 * 글씨가 없으면 null 을 반환한다.
 */
export function 글씨영역_자르기(그림) {
  const { 너비, 높이, 화소 } = 그림;
  let 위 = 높이, 왼쪽 = 너비, 아래 = -1, 오른쪽 = -1;

  for (let y = 0; y < 높이; y += 1) {
    for (let x = 0; x < 너비; x += 1) {
      if (화소[y * 너비 + x] > 30) {
        if (y < 위) 위 = y;
        if (y > 아래) 아래 = y;
        if (x < 왼쪽) 왼쪽 = x;
        if (x > 오른쪽) 오른쪽 = x;
      }
    }
  }

  if (아래 < 0) return null;

  const 새너비 = 오른쪽 - 왼쪽 + 1;
  const 새높이 = 아래 - 위 + 1;
  const 잘린화소 = new Uint8ClampedArray(새너비 * 새높이);
  for (let y = 0; y < 새높이; y += 1) {
    for (let x = 0; x < 새너비; x += 1) {
      잘린화소[y * 새너비 + x] = 화소[(위 + y) * 너비 + (왼쪽 + x)];
    }
  }
  return 그림만들기(새너비, 새높이, 잘린화소);
}

/**
 * 글씨의 무게중심을 28x28 의 정중앙(13.5, 13.5)으로 옮긴다.
 *
 * 이 단계를 빼면 눈에 띄게 틀린다. MNIST 가 이렇게 정렬된 데이터이기 때문이다.
 * PIL 의 AFFINE 변환은 출력 좌표에서 입력 좌표를 역산하므로
 * 출력(x, y) = 입력(x - 이동x, y - 이동y) 가 된다. 정수 이동이라 보간이 없다.
 */
export function 무게중심_이동(그림) {
  const { 너비, 높이, 화소 } = 그림;
  let 총합 = 0;
  let 가중x = 0;
  let 가중y = 0;

  for (let y = 0; y < 높이; y += 1) {
    for (let x = 0; x < 너비; x += 1) {
      const 값 = 화소[y * 너비 + x];
      총합 += 값;
      가중x += x * 값;
      가중y += y * 값;
    }
  }

  if (총합 === 0) return 그림;          // 빈 그림이면 그대로 둔다

  const 이동x = 파이썬_반올림(13.5 - 가중x / 총합);
  const 이동y = 파이썬_반올림(13.5 - 가중y / 총합);
  if (이동x === 0 && 이동y === 0) return 그림;

  const 옮긴화소 = new Uint8ClampedArray(너비 * 높이);
  for (let y = 0; y < 높이; y += 1) {
    const 원본y = y - 이동y;
    if (원본y < 0 || 원본y >= 높이) continue;
    for (let x = 0; x < 너비; x += 1) {
      const 원본x = x - 이동x;
      if (원본x < 0 || 원본x >= 너비) continue;
      옮긴화소[y * 너비 + x] = 화소[원본y * 너비 + 원본x];
    }
  }
  return 그림만들기(너비, 높이, 옮긴화소);
}

/** 태스크 7 에서 구현한다. */
export function 란초스_크기변경(그림, 새너비, 새높이) {
  throw new Error("란초스_크기변경 미구현");
}

/**
 * 임의 크기 손글씨 그림을 28x28 MNIST 규격으로 바꾼다.
 *
 * preprocess.py 의 MNIST형식으로_변환 과 같은 순서다.
 */
export function MNIST형식으로_변환(그림) {
  const 회색 = 배경이_밝으면_반전(그림);
  const 잘린 = 글씨영역_자르기(회색);

  // 아무것도 그리지 않은 경우: 빈 검은 이미지를 반환한다
  if (잘린 === null) return 그림만들기(28, 28);

  // 가로세로 비율을 유지한 채 긴 변이 20픽셀이 되도록 바꾼다
  const 비율 = 20.0 / Math.max(잘린.너비, 잘린.높이);
  const 새너비 = Math.max(1, 파이썬_반올림(잘린.너비 * 비율));
  const 새높이 = Math.max(1, 파이썬_반올림(잘린.높이 * 비율));
  const 축소 = 란초스_크기변경(잘린, 새너비, 새높이);

  // 28x28 검은 캔버스 중앙에 붙인다
  const 결과 = 그림만들기(28, 28);
  const 시작x = (28 - 새너비) >> 1;
  const 시작y = (28 - 새높이) >> 1;
  for (let y = 0; y < 새높이; y += 1) {
    for (let x = 0; x < 새너비; x += 1) {
      결과.화소[(시작y + y) * 28 + (시작x + x)] = 축소.화소[y * 새너비 + x];
    }
  }

  return 무게중심_이동(결과);
}
