"""
파이썬 쪽 내보내기 로직을 검사하는 스크립트.

테스트 프레임워크를 쓰지 않는 저장소라 평범한 스크립트로 만들었다.

실행:
    python self_check.py
"""

import base64
import json
import math
import sys
from pathlib import Path

import torch
import torch.nn.functional as F

from export_weights import (
    배치정규화_접기, 접은_레이어들, 학습된_모델_읽기, 시험무늬_만들기,
)

현재폴더 = Path(__file__).resolve().parent

실패목록 = []


def 단언(조건: bool, 설명: str):
    """조건이 거짓이면 실패로 기록한다. 예외를 던지지 않고 끝까지 검사한다."""
    if not 조건:
        실패목록.append(설명)
        print(f"  [실패] {설명}")
    else:
        print(f"  [통과] {설명}")


def 검사_배치정규화_접기():
    """접은 합성곱의 출력이 원래 '합성곱 -> 배치정규화' 와 같아야 한다."""
    print("검사: 배치정규화 접기")
    모델 = 학습된_모델_읽기()
    입력 = torch.randn(4, 1, 28, 28)

    with torch.no_grad():
        원래 = 모델.정규화1(모델.합성곱1(입력))
        새가중치, 새편향 = 배치정규화_접기(모델.합성곱1, 모델.정규화1)
        접은결과 = F.conv2d(입력, 새가중치, 새편향, padding=1)

    최대오차 = (원래 - 접은결과).abs().max().item()
    단언(최대오차 < 1e-5, f"합성곱1 접기 최대오차 {최대오차:.2e} < 1e-5")

    with torch.no_grad():
        중간 = F.max_pool2d(F.relu(원래), 2)
        원래2 = 모델.정규화2(모델.합성곱2(중간))
        새가중치2, 새편향2 = 배치정규화_접기(모델.합성곱2, 모델.정규화2)
        접은결과2 = F.conv2d(중간, 새가중치2, 새편향2, padding=1)

    최대오차2 = (원래2 - 접은결과2).abs().max().item()
    단언(최대오차2 < 1e-5, f"합성곱2 접기 최대오차 {최대오차2:.2e} < 1e-5")


def 검사_레이어_목록():
    """내보낼 레이어의 개수, 이름, 원소 수가 설계와 같아야 한다."""
    print("검사: 레이어 목록")
    모델 = 학습된_모델_읽기()
    레이어들 = 접은_레이어들(모델)

    기대이름 = [
        "합성곱1.가중치", "합성곱1.편향",
        "합성곱2.가중치", "합성곱2.편향",
        "전결합1.가중치", "전결합1.편향",
        "전결합2.가중치", "전결합2.편향",
    ]
    단언([이름 for 이름, _ in 레이어들] == 기대이름, "레이어 이름과 순서")

    전체 = sum(텐서.numel() for _, 텐서 in 레이어들)
    단언(전체 == 421642, f"전체 원소 수 {전체} == 421642")


def 검사_검증샘플():
    """verify_samples.json 의 구조와 내용이 앞뒤가 맞아야 한다."""
    print("검사: 검증 샘플")
    경로 = 현재폴더.parent / "web_version" / "weights" / "verify_samples.json"
    단언(경로.exists(), "verify_samples.json 이 존재")
    if not 경로.exists():
        return

    묶음 = json.loads(경로.read_text(encoding="utf-8"))
    샘플수 = 묶음["샘플수"]
    단언(샘플수 == 200, f"샘플 수 {샘플수} == 200")

    원본 = base64.b64decode(묶음["원본28x28_base64"])
    전처리 = base64.b64decode(묶음["기대_전처리28x28_base64"])
    단언(len(원본) == 샘플수 * 784, f"원본 바이트 {len(원본)} == {샘플수 * 784}")
    단언(len(전처리) == 샘플수 * 784, f"전처리 바이트 {len(전처리)} == {샘플수 * 784}")

    단언(len(묶음["기대_로짓"]) == 샘플수, "로짓 개수")
    단언(all(len(줄) == 10 for 줄 in 묶음["기대_로짓"]), "로짓마다 10개")

    # 로그 확률이므로 exp 의 합이 1 이어야 한다
    최대편차 = 0.0
    for 줄 in 묶음["기대_로짓"]:
        합 = sum(math.exp(값) for 값 in 줄)
        최대편차 = max(최대편차, abs(합 - 1.0))
    단언(최대편차 < 1e-4, f"exp(로짓) 합의 최대 편차 {최대편차:.2e} < 1e-4")

    # 내보낸 파이프라인이 실제로 쓸 만한지 (모델 성능 확인이지 이식 검증은 아니다)
    맞은수 = sum(
        1 for 줄, 정답 in zip(묶음["기대_로짓"], 묶음["정답"])
        if max(range(10), key=lambda i: 줄[i]) == 정답
    )
    단언(맞은수 >= 190, f"기대 로짓 기준 정답 {맞은수}/200 >= 190")

    시험 = 묶음["축소_시험"]
    입력 = base64.b64decode(시험["입력_base64"])
    출력 = base64.b64decode(시험["출력_base64"])
    단언(len(입력) == 시험["입력크기"] ** 2, "축소 시험 입력 크기")
    단언(len(출력) == 시험["출력크기"] ** 2, "축소 시험 출력 크기")

    # 무늬가 난수에 의존하지 않아야 한다. 의존하면 다시 내보낼 때마다
    # 자바스크립트 쪽 기대값이 바뀌어 대조가 무의미해진다.
    다시만든무늬 = 시험무늬_만들기()
    단언(
        다시만든무늬.tobytes() == 입력,
        "시험무늬_만들기() 가 매번 같은 무늬를 만든다",
    )


def main():
    검사_배치정규화_접기()
    검사_레이어_목록()
    검사_검증샘플()

    print()
    if 실패목록:
        print(f"실패 {len(실패목록)} 건")
        sys.exit(1)
    print("모두 통과")


if __name__ == "__main__":
    main()
